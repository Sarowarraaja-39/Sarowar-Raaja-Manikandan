import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {profile,career,projects} from '../src/data/portfolio.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
assert.equal(projects.length,6,'Preserve the five existing projects and the new professional documentation case.');
assert.equal(new Set(projects.map(p=>p.id)).size,projects.length);
const l1=career.find(c=>c.id==='presto-l1');const l2=career.find(c=>c.id==='presto-l2');
assert(l1&&l2,'Presto must have distinct L1 and L2 entries.');
assert.match(l1.role,/L1 Network Engineer/);
assert.match(l1.paragraphs.join(' '),/bridge between customers and L2/);
assert.match(l1.paragraphs.join(' '),/After resolution/);
assert.match(l1.bullets.join(' '),/RCA/);
assert.match(l2.bullets.join(' '),/migrations/i);
assert(l2.facts.some(f=>f.value==='341'));
assert.equal(l1.period,l2.period,'Do not invent role-specific promotion dates.');
assert.match(projects.find(p=>p.id==='twinshield').metricNote,/Dataset, split/);
assert.equal(projects.find(p=>p.id==='safe').status,'Research concept');
assert.equal(projects.find(p=>p.id==='securefi').status,'Architecture / design');
const documentation=projects.find(p=>p.id==='evidence');
assert(documentation.metrics.some(m=>m.value==='365+'&&/MOP/.test(m.label)),'Documentation coverage must not become a migration execution claim.');
assert.match(documentation.status,/repository pending/);
assert.match(documentation.metricNote,/separate from the number of migrations/);
const bp=career.find(c=>c.id==='bp');
assert.equal(bp.period,'February 2026 — present');
assert.equal(bp.role,'Customer Assistant');
assert(!/over one year|cybersecurity analyst|SOC analyst/i.test([bp.role,...bp.paragraphs,...bp.bullets].join(' ')),'Keep the supplied BP dates and operational responsibilities accurate.');
assert(profile.email.includes('@'));
for(const file of ['public/assets/sarowar-editorial.png','public/assets/sarowar-original.jpg'])assert(fs.statSync(path.join(root,file)).size>10000,`${file} is missing or empty.`);
console.log('Content checks passed: six projects, distinct documentation/migration figures, separate Presto roles, current BP dates, scoped claims and portraits.');
